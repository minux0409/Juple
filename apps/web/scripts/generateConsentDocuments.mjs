// Web is built with apps/web as its Docker context. Keep its self-contained inputs synchronized with the source contracts.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const check = process.argv.includes('--check');
// Cross-project source parity belongs here, not in the self-contained Web test/build context.
// Check mode must fail on missing/stale inputs; it never regenerates or silently skips them.
function sync(relativePath, expected) {
  const target = new URL(relativePath, root);
  if (check) {
    const actual = readFileSync(target);
    // Git checkouts may use CRLF while Docker/archive sources use LF.
    // JSON sources remain byte-exact; TypeScript source parity ignores only line endings.
    const matches = typeof expected === 'string'
      ? actual.toString('utf8').replace(/\r\n/g, '\n') === expected.replace(/\r\n/g, '\n')
      : actual.equals(expected);
    if (!matches) {
      throw new Error(`${relativePath} is stale. Run scripts/generateConsentDocuments.mjs from the full repository.`);
    }
  } else {
    writeFileSync(target, expected);
  }
}
sync('lib/publishedTerms.generated.json', readFileSync(new URL('../../backend/src/Juple.Application/Safety/PublishedTerms.json', root)));
sync('lib/legacyPublishedTerms.generated.json', readFileSync(new URL('../../backend/src/Juple.Application/Safety/LegacyPublishedTerms.json', root)));
sync('lib/archivedPublishedTerms.generated.json', readFileSync(new URL('../../backend/src/Juple.Application/Safety/ArchivedPublishedTerms.json', root)));
const parser = readFileSync(new URL('../mobile/src/safety/termsDocument.ts', root), 'utf8');
sync('lib/termsDocument.generated.ts', '// Generated by scripts/generateConsentDocuments.mjs. Edit the Mobile source contract, then regenerate.\n' + parser);
sync('lib/legalDocumentPolicy.generated.ts', '// Generated by scripts/generateConsentDocuments.mjs. Edit Mobile i18n/legalDocumentPolicy.ts, then regenerate.\n' + readFileSync(new URL('../mobile/src/i18n/legalDocumentPolicy.ts', root), 'utf8'));
console.log(check ? 'Consent source parity: PASS (5 generated files)' : 'Generated 5 consent files.');
